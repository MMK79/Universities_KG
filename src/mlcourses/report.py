"""Summary statistics from the database -> docs/findings-data.md (regenerated each run)."""

from __future__ import annotations

from .config import ROOT
from .db import connect

QUERIES = {
    "coverage": """
      SELECT count(*) AS universities,
             count(*) FILTER (WHERE EXISTS (SELECT 1 FROM courses c WHERE c.university_id=u.id))
               AS with_ml_course,
             count(*) FILTER (WHERE EXISTS (SELECT 1 FROM courses c WHERE c.university_id=u.id
                                             AND c.topic='ml-core')) AS with_core_ml_course,
             count(*) FILTER (WHERE EXISTS (
                SELECT 1 FROM courses c JOIN course_offerings o ON o.course_id=c.id
                JOIN course_books cb ON cb.offering_id=o.id
                WHERE c.university_id=u.id AND cb.book_id IS NOT NULL)) AS with_matched_book,
             count(*) FILTER (WHERE EXISTS (
                SELECT 1 FROM courses c JOIN course_offerings o ON o.course_id=c.id
                JOIN course_books cb ON cb.offering_id=o.id
                WHERE c.university_id=u.id)) AS with_any_reference
      FROM universities u WHERE %(subset)s = ANY(u.subset_tags)""",
    "adoption": """
      SELECT b.title, b.authors, count(DISTINCT c.university_id) AS universities,
             count(DISTINCT o.id) AS offerings,
             round(avg(cb.confidence)::numeric, 2) AS mean_conf
      FROM course_books cb JOIN books b ON b.id=cb.book_id
      JOIN course_offerings o ON o.id=cb.offering_id JOIN courses c ON c.id=o.course_id
      JOIN universities u ON u.id=c.university_id
      WHERE %(subset)s = ANY(u.subset_tags)
      GROUP BY b.id ORDER BY universities DESC, offerings DESC""",
    "by_country": """
      SELECT u.country, count(DISTINCT u.id) AS universities,
             count(DISTINCT c.university_id) AS with_ml_course,
             count(DISTINCT c.university_id) FILTER (WHERE cb.book_id IS NOT NULL)
               AS with_matched_book
      FROM universities u LEFT JOIN courses c ON c.university_id=u.id
      LEFT JOIN course_offerings o ON o.course_id=c.id
      LEFT JOIN course_books cb ON cb.offering_id=o.id
      WHERE %(subset)s = ANY(u.subset_tags) GROUP BY u.country ORDER BY u.country""",
    "materials": """
      SELECT m.type, count(*) AS links, count(DISTINCT m.offering_id) AS offerings
      FROM materials m JOIN course_offerings o ON o.id=m.offering_id
      JOIN courses c ON c.id=o.course_id JOIN universities u ON u.id=c.university_id
      WHERE %(subset)s = ANY(u.subset_tags) GROUP BY m.type ORDER BY links DESC""",
    "crawl": """
      SELECT l.kind, l.status, count(*) AS n FROM crawl_log l
      JOIN universities u ON u.id=l.university_id WHERE %(subset)s = ANY(u.subset_tags)
      GROUP BY 1,2 ORDER BY 1,3 DESC""",
    "offerings": """
      SELECT u.name, c.code, left(c.title, 70) AS title, c.topic, c.level, o.term,
             count(cb.book_id) AS books, o.url
      FROM course_offerings o JOIN courses c ON c.id=o.course_id
      JOIN universities u ON u.id=c.university_id
      LEFT JOIN course_books cb ON cb.offering_id=o.id
      WHERE %(subset)s = ANY(u.subset_tags)
      GROUP BY u.name, c.code, c.title, c.topic, c.level, o.term, o.url
      ORDER BY u.name, c.code""",
    "no_course": """
      SELECT u.name, u.country FROM universities u
      WHERE %(subset)s = ANY(u.subset_tags)
        AND NOT EXISTS (SELECT 1 FROM courses c WHERE c.university_id=u.id)
      ORDER BY u.country, u.name""",
}


def md_table(cols: list[str], rows: list[tuple]) -> str:
    def cell(v):
        return "" if v is None else str(v).replace("|", "\\|").replace("\n", " ")

    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(cell(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def run(subset: str) -> str:
    parts = [
        f"# Findings data — subset `{subset}`\n",
        "_Generated by `mlcourses report`; do not edit by hand._\n",
    ]
    with connect() as conn:
        for name, q in QUERIES.items():
            cur = conn.execute(q, {"subset": subset})
            cols = [d.name for d in cur.description]
            parts.append(f"## {name}\n\n{md_table(cols, cur.fetchall())}\n")
    text = "\n".join(parts)
    (ROOT / "docs" / "findings-data.md").write_text(text)
    return text
